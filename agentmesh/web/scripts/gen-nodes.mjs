// Generates src/runtime/agents.generated.ts from the three agent definitions (node ids, types, descriptions,
// model tiers, tools). It never copies URLs or prompts. Run after a Builder re-export:  npm run gen:nodes
//   source order: ../hosts/<agent>/definitions/<agent>.yaml, then ../../inputs/yaml/<agent>.yaml
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const here = dirname(fileURLToPath(import.meta.url));
const AGENTS = ["handover-orchestrator", "handover-qa", "handover-kt-session"];
const HUMAN = new Set(["hitl_gate", "ask_user"]);

const out = {};
for (const agent of AGENTS) {
  const candidates = [
    resolve(here, `../../hosts/${agent}/definitions/${agent}.yaml`),
    resolve(here, `../../../inputs/yaml/${agent}.yaml`),
  ];
  const file = candidates.find(existsSync);
  if (!file) throw new Error(`No definition found for ${agent} (looked in ${candidates.join(", ")})`);
  const doc = parse(readFileSync(file, "utf8"));
  const nodes = (doc.nodes ?? []).map((n) => {
    const id = n.name ?? n.id;
    const node = { id, type: n.type, description: String(n.description ?? "").replace(/https?:\/\/\S+/g, "") };
    if (n.model) node.model = String(n.model);
    if (n.tool) node.tool = String(n.tool);
    if (n.type === "subgraph_call" && n.agent) node.tool = String(n.agent);
    if (HUMAN.has(n.type)) node.human = true;
    return node;
  });
  const edges = (doc.edges ?? []).map((e) => ({ from: e.from, to: e.to, ...(e.condition ? { conditional: true } : {}) }));
  out[agent] = {
    name: agent,
    description: String(doc.metadata?.description ?? ""),
    governance: String(doc.metadata?.governance_level ?? ""),
    nodes,
    edges,
  };
}

const target = resolve(here, "../src/runtime/agents.generated.ts");
writeFileSync(
  target,
  `// GENERATED by scripts/gen-nodes.mjs from the AgentMesh agent definitions. Do not edit by hand.\n` +
    `import type { AgentDefinitionSummary } from "./types";\n\n` +
    `export const AGENT_DEFINITIONS: Record<string, AgentDefinitionSummary> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(`wrote ${target}: ` + AGENTS.map((a) => `${a} ${out[a].nodes.length} nodes`).join(", "));
